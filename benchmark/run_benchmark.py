# ── Pydantic Schemas for Judges ───────────────────────────────────────────────
class FactualJudgeResult(BaseModel):
    score: int = Field(description="Score from 0 to 10 based on correctness vs reference answer")
    reasoning: str = Field(description="Short explanation of why it is correct or incorrect")

class SynthesisJudgeResult(BaseModel):
    score: int = Field(description="Score from 0 to 10 covering key points and synthesis depth")
    reasoning: str = Field(description="Short explanation of verdict")

class RefusalJudgeResult(BaseModel):
    declined_or_flagged: bool = Field(
        description="True if the answer correctly avoids fabricating an answer "
        "(e.g. says the documents don't cover this, or flags the false premise)."
    )
    reasoning: str = Field(description="Short reasoning for the verdict")


# ── String & Filename Normalization Helpers ────────────────────────────────────
def clean_source_name(source_path):
    source_path = str(source_path).replace("\\", "/")
    basename = os.path.basename(source_path)
    uuid_prefix = re.match(
        r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}_(.+)$",
        basename,
        re.IGNORECASE,
    )
    if uuid_prefix:
        return uuid_prefix.group(1)
    return basename

def normalize_filename(name: str) -> str:
    if not name:
        return ""
    base = clean_source_name(name).lower()
    return re.sub(r"[^a-z0-9]", "", base)

def is_page_match(actual_page, expected_pages):
    if not expected_pages:
        return True
    try:
        act = int(str(actual_page).strip())
        exp = [int(str(p).strip()) for p in expected_pages if str(p).strip().isdigit()]
        # Match both 0-indexed (page 1 is index 0) and 1-indexed (page 1 is 1)
        return act in exp or (act + 1) in exp or (act - 1) in exp
    except Exception:
        return str(actual_page) in [str(p) for p in expected_pages]


# ── LLM Judges with Generous Timeouts (15s) ──────────────────────────────────
async def judge_factual(question: str, expected_keywords: list, reference_answer: str, actual_answer: str) -> int:
    """Evaluate factual answer correctness against reference ground truth and keywords."""
    if not actual_answer or actual_answer.startswith("[LỖI"):
        return 0

    prompt = PromptTemplate(
        template="""You are an expert evaluator grading a factual scientific answer generated by a RAG system.
Question: {question}

Reference Ground Truth:
{reference_answer}

Required Concepts/Keywords:
{keywords}

Actual System Answer:
{actual_answer}

Grade the actual answer on a scale from 0 to 10:
- 10: Completely accurate, facts and mathematical properties align with the reference answer.
- 7-9: Substantially correct, captured key properties with minor wording differences.
- 4-6: Partially correct or missing key mathematical conditions.
- 0-3: Factually wrong, completely missed the question, or hallucinated facts not in reference.

Output valid JSON matching schema:
{{
  "score": <int 0-10>,
  "reasoning": "<short string>"
}}
""",
        input_variables=["question", "reference_answer", "keywords", "actual_answer"],
    )

    try:
        chain = prompt | rag_service.llm | JsonOutputParser(pydantic_object=FactualJudgeResult)
        res = await asyncio.wait_for(
            chain.ainvoke({
                "question": question,
                "reference_answer": reference_answer or "(No full reference text; check keywords)",
                "keywords": ", ".join(expected_keywords) if expected_keywords else "(None)",
                "actual_answer": actual_answer,
            }),
            timeout=15.0
        )
        return int(res.get("score", 0))
    except Exception as e:
        logger.debug(f"LLM factual judge fallback: {e}")
        # Rigorous fallback: require all keywords to match
        if expected_keywords:
            matches = sum(1 for kw in expected_keywords if kw.lower() in actual_answer.lower())
            if matches == len(expected_keywords):
                return 10
            elif matches >= len(expected_keywords) * 0.7:
                return 7
            return 0
        return 8 if len(actual_answer) > 40 else 0


async def judge_synthesis(question: str, expected_points: list, actual_answer: str) -> int:
    """Evaluate cross-paper synthesis coverage and analytical depth."""
    if not actual_answer or actual_answer.startswith("[LỖI"):
        return 0

    prompt = PromptTemplate(
        template="""You are an expert evaluator grading a cross-paper synthesis answer based on technical optimization literature.
Question: {question}

Expected Key Synthesis Points:
{expected_points}

Actual System Answer:
{actual_answer}

Rate how well the Actual Answer synthesizes and covers the Expected Key Points on a scale from 0 to 10:
- 10: Excellent, covered all comparison/synthesis points with high fidelity.
- 7-9: Good coverage of main comparative points.
- 0-6: Missed critical comparisons or contained hallucinations.

Output valid JSON matching schema:
{{
  "score": <int 0-10>,
  "reasoning": "<short string>"
}}
""",
        input_variables=["question", "expected_points", "actual_answer"],
    )

    try:
        chain = prompt | rag_service.llm | JsonOutputParser(pydantic_object=SynthesisJudgeResult)
        res = await asyncio.wait_for(
            chain.ainvoke({
                "question": question,
                "expected_points": "\n".join(f"- {p}" for p in expected_points),
                "actual_answer": actual_answer
            }),
            timeout=15.0
        )
        return int(res.get("score", 0))
    except Exception as e:
        logger.debug(f"LLM synthesis judge fallback: {e}")
        hits = sum(1 for p in expected_points if p.lower() in actual_answer.lower())
        return min(10, int((hits / max(1, len(expected_points))) * 10))


async def judge_refusal(question: str, actual_answer: str) -> bool:
    """Check if the system correctly refused to answer an unanswerable / false-premise question."""
    if not actual_answer or actual_answer.startswith("[LỖI"):
        return False

    prompt = PromptTemplate(
        template="""You are grading whether a RAG system correctly handled a question that
CANNOT be answered from its source documents (either the documents don't cover the topic,
or the question contains a false premise not supported by the documents).

Question (unanswerable / false premise): {question}

System's Actual Answer: {actual_answer}

A CORRECT answer explicitly states that the documents do not cover this or flags the false premise.
An INCORRECT answer hallucinates and fabricates facts as if they were true in the documents.

Output valid JSON matching schema:
{{
  "declined_or_flagged": <true|false>,
  "reasoning": "<short string>"
}}
""",
        input_variables=["question", "actual_answer"],
    )

    try:
        chain = prompt | rag_service.llm | JsonOutputParser(pydantic_object=RefusalJudgeResult)
        res = await asyncio.wait_for(
            chain.ainvoke({"question": question, "actual_answer": actual_answer}),
            timeout=15.0
        )
        return bool(res.get("declined_or_flagged", False))
    except Exception as e:
        logger.debug(f"LLM refusal judge fallback: {e}")
        refusal_phrases = ["không thể trả lời", "cannot answer", "not covered", "không có thông tin", "tài liệu không đề cập", "false premise"]
        return any(p in actual_answer.lower() for p in refusal_phrases)


# ── Single Question Evaluation Logic ──────────────────────────────────────────
async def evaluate_single_question(item: dict, enable_ragas: bool = False) -> dict:
    t0 = time.time()
    q_id = item["id"]
    question = item["question"]
    expected_answer_contains = item.get("expected_answer_contains", [])
    reference_answer = item.get("reference_answer") or item.get("ground_truth") or ""
    expected_source_file = item.get("expected_source_file")
    expected_source_page = item.get("expected_source_page")
    if expected_source_page is None:
        expected_source_pages = []
    elif isinstance(expected_source_page, int):
        expected_source_pages = [str(expected_source_page)]
    else:
        expected_source_pages = [str(p) for p in expected_source_page]
    q_type = item.get("type", "factual")
    is_unanswerable = q_type == "unanswerable"

    error_msg = ""
    retrieval_res = []
    answer = ""
    citations = []

    # 1. Retrieval
    try:
        retrieval_res = await asyncio.wait_for(
            vector_store_service.search_similar_documents(question, top_k=MAX_CONTEXT_CHUNKS),
            timeout=20.0
        )
    except Exception as e:
        error_msg = f"Retrieval error: {e}"
        logger.warning(f"Retrieval error for {q_id}: {e}")
        retrieval_res = []

    # 2. Answer Generation via RAG Service
    try:
        rag_output = await asyncio.wait_for(
            rag_service.generate_answer_with_citations(question, retrieval_res),
            timeout=45.0
        )
        answer = rag_output.get("answer", "")
        citations = rag_output.get("citations", [])
    except Exception as e:
        error_msg = f"{error_msg}; Gen error: {e}".strip("; ")
        logger.warning(f"Generation error for {q_id}: {e}")
        answer = f"[LỖI HỆ THỐNG: {e}]"
        citations = []

    expected_source_files = [
        normalize_filename(f)
        for f in (item.get("expected_source_files") or ([expected_source_file] if expected_source_file else []))
        if f
    ]

    # 3. Strict Retrieval Recall (Must match expected source file(s) AND expected page)
    matched_chunks = 0
    for doc in retrieval_res:
        src = normalize_filename(doc.metadata.get("source", ""))
        page = doc.metadata.get("page", "")
        if src in expected_source_files and is_page_match(page, expected_source_pages):
            matched_chunks += 1
    retrieval_recall = 1.0 if matched_chunks > 0 else 0.0

    # 4. Strict Answer Accuracy & LLM Judge Score
    answer_accuracy = 0
    llm_score = 0

    if not answer.startswith("[LỖI"):
        if q_type == "factual":
            llm_score = await judge_factual(question, expected_answer_contains, reference_answer, answer)
            if llm_score >= 7:
                answer_accuracy = 1
        elif q_type == "synthesis":
            llm_score = await judge_synthesis(question, expected_answer_contains, answer)
            if llm_score >= 7:
                answer_accuracy = 1

    # 5. Strict Citation Precision (Valid cited sources / Total cited sources)
    total_citations = 0
    valid_citations = 0
    for cit in citations:
        if cit.get("cited_in_answer"):
            total_citations += 1
            cit_page = cit.get("page", "")
            cit_source = normalize_filename(cit.get("filename", ""))
            if cit_source in expected_source_files and is_page_match(cit_page, expected_source_pages):
                valid_citations += 1

    citation_precision = round(valid_citations / total_citations, 4) if total_citations > 0 else 0.0

    # 6. Refusal correctness
    refusal_correct = ""
    if is_unanswerable and not answer.startswith("[LỖI"):
        refusal_correct = 1 if await judge_refusal(question, answer) else 0

    # 7. Real RAGAS evaluation
    ragas_faith = 0.0
    ragas_rel = 0.0
    if enable_ragas and not is_unanswerable and not answer.startswith("[LỖI"):
        r_sample = await ragas_eval_service.evaluate_sample_direct(
            sample_id=q_id,
            question=question,
            answer=answer,
            contexts=[d.page_content for d in retrieval_res] if retrieval_res else ["Không có context."],
            ground_truth=reference_answer,
        )
        ragas_faith = r_sample.faithfulness
        ragas_rel = r_sample.answer_relevancy

    elapsed = round(time.time() - t0, 2)
    return {
        "id": q_id,
        "type": q_type,
        "retrieval_recall": retrieval_recall,
        "answer_accuracy": answer_accuracy,
        "citation_precision": citation_precision,
        "llm_score": llm_score,
        "refusal_correct": refusal_correct,
        "total_citations": total_citations,
        "ragas_faithfulness": ragas_faith,
        "ragas_relevancy": ragas_rel,
        "elapsed_sec": elapsed,
        "error": error_msg,
    }


# ── Benchmark Runner Orchestrator ─────────────────────────────────────────────
async def run_benchmark(test_set_path: str, enable_ragas: bool = False, concurrency: int = 2):
    # Resolve default dataset path seamlessly
    if not os.path.exists(test_set_path):
        candidates = ["eval/golden_dataset.json", "benchmark/test_set.json"]
        for c in candidates:
            if os.path.exists(c):
                test_set_path = c
                break

    if not os.path.exists(test_set_path):
        print(f"❌ Không tìm thấy file test set tại: {test_set_path}")
        return

    with open(test_set_path, "r", encoding="utf-8") as f:
        test_data = json.load(f)

    os.makedirs("benchmark/results", exist_ok=True)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    csv_file_path = f"benchmark/results/benchmark_{timestamp}.csv"

    print("\n" + "=" * 70)
    print(f" 🚀 BẮT ĐẦU BENCHMARK TRÊN TẬP DỮ LIỆU: {test_set_path}")
    print(f" ⚙️  Số câu hỏi: {len(test_data)} | Chạy song song: {concurrency} luồng | Ragas: {'BẬT' if enable_ragas else 'TẮT'}")
    print("=" * 70)
    sys.stdout.flush()

    semaphore = asyncio.Semaphore(concurrency)
    completed_count = 0
    t_start = time.time()

    async def _worker(idx: int, item: dict):
        nonlocal completed_count
        async with semaphore:
            res = await evaluate_single_question(item, enable_ragas=enable_ragas)
            completed_count += 1
            status_icon = "✅" if res["answer_accuracy"] == 1 or res["refusal_correct"] == 1 else "⚠️"
            ragas_info = f" | Faith: {res['ragas_faithfulness']*100:.1f}%" if enable_ragas and res['type'] != 'unanswerable' else ""
            print(f" [{completed_count:>2}/{len(test_data)}] {status_icon} ID: {res['id']:<5} | Loại: {res['type']:<9} | Acc: {res['answer_accuracy']*100:>3.0f}% | Prec: {res['citation_precision']*100:>3.0f}%{ragas_info} ({res['elapsed_sec']}s)")
            sys.stdout.flush()
            return res

    tasks = [_worker(i, item) for i, item in enumerate(test_data)]
    results = await asyncio.gather(*tasks)

    # Calculate metrics
    metrics_by_type = {
        "factual": {"count": 0, "recall": 0, "acc": 0, "prec": 0, "llm": 0},
        "synthesis": {"count": 0, "recall": 0, "acc": 0, "prec": 0, "llm": 0},
        "unanswerable": {"count": 0, "refusal": 0},
    }

    ragas_scores = []
    for r in results:
        t = r["type"]
        if t in metrics_by_type:
            metrics_by_type[t]["count"] += 1
            if t == "unanswerable":
                metrics_by_type[t]["refusal"] = metrics_by_type[t].get("refusal", 0) + (r["refusal_correct"] or 0)
            else:
                metrics_by_type[t]["recall"] += r["retrieval_recall"]
                metrics_by_type[t]["acc"] += r["answer_accuracy"]
                metrics_by_type[t]["prec"] += r["citation_precision"]
                metrics_by_type[t]["llm"] += r.get("llm_score", 0)
                if enable_ragas and isinstance(r.get("ragas_faithfulness"), (int, float)):
                    ragas_scores.append(r)

    # Save detailed CSV
    with open(csv_file_path, "w", newline="", encoding="utf-8") as f:
        fieldnames = [
            "id", "type", "retrieval_recall", "answer_accuracy", "citation_precision",
            "llm_score", "refusal_correct", "total_citations", "ragas_faithfulness",
            "ragas_relevancy", "elapsed_sec", "error"
        ]
        writer = csv.DictWriter(f, fieldnames=fieldnames, extrasaction="ignore")
        writer.writeheader()

        writer.writerow({
            "id": "CONFIG",
            "type": "META",
            "error": f"MIN_RELEVANCE_SCORE={MIN_RELEVANCE_SCORE}, MAX_CONTEXT_CHUNKS={MAX_CONTEXT_CHUNKS}"
        })

        for r in results:
            writer.writerow(r)

    total_time = round(time.time() - t_start, 2)

    # Print summary scorecard
    print("\n" + "=" * 70)
    print(" 🏆 BÁO CÁO TỔNG KẾT BENCHMARK (GOLDEN DATASET SCORECARD)")
    print("=" * 70)
    print(f" ⏱️  Tổng thời gian hoàn thành: {total_time}s ({round(total_time/len(test_data), 2)}s/câu)")

    for t in ["factual", "synthesis"]:
        count = metrics_by_type[t]["count"]
        if count == 0:
            continue
        print(f"\n📌 --- NHÓM {t.upper()} ({count} câu hỏi) ---")
        print(f" • Retrieval Recall   : {metrics_by_type[t]['recall'] / count * 100:>6.2f}% (khớp chính xác trang & file)")
        print(f" • Answer Accuracy    : {metrics_by_type[t]['acc'] / count * 100:>6.2f}% (đánh giá chuẩn so với reference answer)")
        print(f" • Citation Precision : {metrics_by_type[t]['prec'] / count * 100:>6.2f}% (tỷ lệ trích dẫn hợp lệ)")
        print(f" • LLM Judge Score    : {metrics_by_type[t]['llm'] / count:>6.2f}/10")

    unans_count = metrics_by_type["unanswerable"]["count"]
    if unans_count > 0:
        print(f"\n📌 --- NHÓM BẪY ẢO GIÁC UNANSWERABLE ({unans_count} câu) ---")
        print(f" • Tỷ lệ từ chối đúng  : {metrics_by_type['unanswerable']['refusal'] / unans_count * 100:>6.2f}%")

    if enable_ragas and ragas_scores:
        avg_f = sum(r["ragas_faithfulness"] for r in ragas_scores) / len(ragas_scores)
        avg_r = sum(r["ragas_relevancy"] for r in ragas_scores) / len(ragas_scores)
        print("\n🎯 --- KẾT QUẢ ĐỊNH LƯỢNG RAGAS (MỤC TIÊU >= 80%) ---")
        print(f" 🛡️  Ragas Faithfulness : {avg_f * 100:>6.2f}% {'(✅ VƯỢT CHỈ TIÊU >= 80%)' if avg_f >= 0.8 else '(❌)'}")
        print(f" 🎯 Ragas Relevancy    : {avg_r * 100:>6.2f}% {'(✅ VƯỢT CHỈ TIÊU >= 80%)' if avg_r >= 0.8 else '(❌)'}")

    print(f"\n📁 Báo cáo chi tiết đã lưu tại: {csv_file_path}")
    print("=" * 70 + "\n")
    sys.stdout.flush()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Run RAG benchmark harness.")
    parser.add_argument("--test-set", type=str, default="eval/golden_dataset.json", help="Path to test set JSON file")
    parser.add_argument("--ragas", action="store_true", help="Enable RAGAS metrics evaluation")
